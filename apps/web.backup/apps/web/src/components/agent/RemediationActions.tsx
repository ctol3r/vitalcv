import { useMemo, useState } from 'react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Progress } from '@/components/ui/progress';
import { Separator } from '@/components/ui/separator';
import { cn } from '@/lib/utils';
import { AlertTriangle, ArrowRight, CheckCircle2, Clock, FileText, Loader2, RefreshCcw } from 'lucide-react';

export type RemediationSeverity = 'critical' | 'high' | 'medium' | 'low';

export interface RemediationActionEvidence {
  id: string;
  label: string;
  type: 'PSV' | 'PECOS' | 'CAQH' | 'DRIFT' | 'NOTE' | 'OTHER';
  reference?: string;
}

export interface RemediationAction {
  id: string;
  title: string;
  description: string;
  severity: RemediationSeverity;
  dueDate?: string;
  recommendedBy: string;
  workflow: 'license' | 'pecos' | 'caqh' | 'drift' | 'compliance';
  evidence: RemediationActionEvidence[];
  ctaLabel?: string;
}

export interface RemediationActionsProps {
  actions?: RemediationAction[];
  onActionLaunched?: (action: RemediationAction) => void;
}

