function validateStatusHistory(statusEvents: ActionStatusEventRow[]): { duplicateStates: number; invalidTransitions: number } {
  const chronological = [...statusEvents].sort((left, right) => left.createdAt.getTime() - right.createdAt.getTime());
  let duplicateStates = 0;
  let invalidTransitions = 0;

  for (let index = 0; index < chronological.length; index += 1) {
    const current = chronological[index]!;
    const previous = index > 0 ? chronological[index - 1] : null;
    const currentStatus = normalizeActionStatus(current.toStatus);

    if (previous) {
      const previousStatus = normalizeActionStatus(previous.toStatus);
      if (previousStatus === currentStatus) {
        duplicateStates += 1;
      }
      if (!canTransitionActionStatus(previousStatus, currentStatus)) {
        invalidTransitions += 1;
      }
    } else if (current.fromStatus !== null) {
      invalidTransitions += 1;
    }
  }

  return { duplicateStates, invalidTransitions };
}

describe('actionEngineService', () => {
  let prismaClient: ActionPrisma;

  beforeEach(() => {
    prismaClient = new InMemoryActionPrisma();
    jest.resetAllMocks();
  });

  it('dedupes duplicate action recommendations during refresh and keeps the strongest candidate', async () => {
    refreshDecisionRecommendationsMock.mockResolvedValue([]);
    const weak = makeRecommendedAction('action_duplicate', {
      priorityScore: 0.41,
      confidence: 0.54,
      explanation: 'Weaker recommendation.',
    });
    const strong = makeRecommendedAction('action_duplicate', {
      priorityScore: 0.9,
      confidence: 0.92,
      explanation: 'Stronger recommendation.',
      recommendedAction: 'Verify credential immediately',
    });
    createActionEngineMock.mockReturnValue({
      generate: jest.fn().mockReturnValue([weak, strong]),
    });
    generateHiringAutomationActionsMock.mockResolvedValue([]);
    queueHiringAutomationSideEffectsMock.mockResolvedValue();

    const persisted = await refreshActionRecommendations('2026-04-22T12:00:00.000Z', prismaClient as never);

    expect(persisted).toHaveLength(1);
    expect(persisted[0]?.actionId).toBe('action_duplicate');
    expect(persisted[0]?.explanation).toBe('Stronger recommendation.');

    const rows = prismaClient.listActionRows();
    expect(rows).toHaveLength(1);
    expect(rows[0]?.priorityScore).toBe(0.9);
    expect(rows[0]?.confidence).toBe(0.92);
  });

  it('keeps independent multi-action workflows isolated and valid', async () => {
    await makeSeededAction(prismaClient, { actionId: 'action_save_then_dismiss', targetEntityId: '1234567890' });
    await makeSeededAction(prismaClient, { actionId: 'action_execute', targetEntityId: '1234567891', targetEntityLabel: 'Grace Hopper' });

    const saved = await saveActionRecommendation('action_save_then_dismiss', {
      actorId: 'ops-user',
      note: 'Parking for follow-up.',
    }, prismaClient as never);
    const executed = await executeActionRecommendation('action_execute', {
      actorId: 'ops-user',
      note: 'Execution completed.',
    }, prismaClient as never);
    const dismissed = await dismissActionRecommendation('action_save_then_dismiss', {
      actorId: 'ops-user',
      note: 'No longer needed.',
    }, prismaClient as never);

    expect(saved.status).toBe('in_progress');
    expect(executed.status).toBe('completed');
    expect(dismissed.status).toBe('skipped');

    const first = prismaClient.getActionWithEvents('action_save_then_dismiss');
    const second = prismaClient.getActionWithEvents('action_execute');

    expect(first?.status).toBe('skipped');
    expect(first?.statusEvents).toHaveLength(3);
    expect(second?.status).toBe('completed');
    expect(second?.statusEvents).toHaveLength(2);
  });

  it('recovers cleanly after a failed dependency check without drifting state', async () => {
    await makeSeededAction(prismaClient, {
      actionId: 'action_ready_with_missing_dependency',
      actionType: 'READY_TO_INTERVIEW',
      metadata: makeHiringMetadata(['Board Certification']),
    });

    await expect(
      executeActionRecommendation('action_ready_with_missing_dependency', {
        actorId: 'ops-user',
        note: 'Attempt to complete before dependency resolution.',
      }, prismaClient as never),
    ).rejects.toThrow('Action has unresolved dependencies');

    await prismaClient.updateActionMetadata('action_ready_with_missing_dependency', makeHiringMetadata([]));

    const recovered = await executeActionRecommendation('action_ready_with_missing_dependency', {
      actorId: 'ops-user',
      note: 'Dependencies cleared.',
    }, prismaClient as never);

    const stored = prismaClient.getActionWithEvents('action_ready_with_missing_dependency');
    const metadata = extractHiringAutomationMetadata(stored?.metadata);

    expect(recovered.status).toBe('completed');
    expect(metadata?.workflowEffects.missingCredentials).toEqual([]);
    expect(stored?.statusEvents).toHaveLength(2);
    expect(stored?.statusEvents?.filter((event) => event.toStatus.toLowerCase() === 'completed')).toHaveLength(1);
  });

  it('treats concurrent execute attempts as one terminal transition', async () => {
    await makeSeededAction(prismaClient, { actionId: 'action_concurrent_execute' });
    prismaClient.enableConcurrentUpdateBarrier(2);

    const [first, second] = await Promise.all([
      executeActionRecommendation('action_concurrent_execute', {
        actorId: 'ops-user-1',
        note: 'Concurrent execute #1',
      }, prismaClient as never),
      executeActionRecommendation('action_concurrent_execute', {
        actorId: 'ops-user-2',
        note: 'Concurrent execute #2',
      }, prismaClient as never),
    ]);

    const stored = prismaClient.getActionWithEvents('action_concurrent_execute');

    expect(first.status).toBe('completed');
    expect(second.status).toBe('completed');
    expect(stored?.status).toBe('completed');
    expect(stored?.statusEvents).toHaveLength(2);
    expect(stored?.statusEvents?.filter((event) => event.toStatus.toLowerCase() === 'completed')).toHaveLength(1);
  });

  it('maintains valid state under 50 clinician workflows with random failures and concurrency', async () => {
    const random = mulberry32(424242);
    const workflowStats = {
      clinicians: 50,
      actionsCompleted: 0,
      actionsSkipped: 0,
      actionsInProgress: 0,
      dependencyBlocks: 0,
      transientFailuresRecovered: 0,
      duplicateTerminalEvents: 0,
      invalidTransitions: 0,
    };

    for (let index = 0; index < workflowStats.clinicians; index += 1) {
      const actionId = `workflow_${index}`;
      const roll = random();
      const actionType = roll < 0.3
        ? 'READY_TO_INTERVIEW'
        : roll < 0.55
          ? 'REQUEST_CREDENTIAL'
          : roll < 0.75
            ? 'CONTINUE_REVIEW'
            : 'VERIFY_CREDENTIAL';
      const missingCredentials = actionType === 'READY_TO_INTERVIEW' && random() < 0.28
        ? ['Board Certification']
        : [];

      await makeSeededAction(prismaClient, {
        actionId,
        actionType,
        targetEntityId: `${1003000000 + index}`,
        targetEntityLabel: `Clinician ${index}`,
        metadata: actionType === 'READY_TO_INTERVIEW'
          ? makeHiringMetadata(missingCredentials)
          : {},
      });

      if (random() < 0.18) {
        prismaClient.injectStatusEventFailure(actionId, 1);
      }
    }

    const workflows = prismaClient.listActionRows().map(async (row, index) => {
      try {
        if (row.actionType === 'READY_TO_INTERVIEW') {
          if (index % 5 === 0) {
            prismaClient.enableConcurrentUpdateBarrier(2);
            await Promise.allSettled([
              executeActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Concurrent execute A' }, prismaClient as never),
              executeActionRecommendation(row.actionId, { actorId: `actor-${index}-b`, note: 'Concurrent execute B' }, prismaClient as never),
            ]);
          }

          try {
            await executeActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Initial execute attempt' }, prismaClient as never);
          } catch (error) {
            const message = error instanceof Error ? error.message : String(error);
            if (message.includes('Invalid action status transition') || message.includes('existingStatus')) {
              return;
            }
            if (message.includes('unresolved dependencies')) {
              workflowStats.dependencyBlocks += 1;
              await prismaClient.updateActionMetadata(row.actionId, makeHiringMetadata([]));
            }
            workflowStats.transientFailuresRecovered += 1;
            try {
              await executeActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Retry after transient failure' }, prismaClient as never);
            } catch {
              // action already in terminal state or second transient failure; acceptable
            }
          }
          return;
        }

        if (row.actionType === 'REQUEST_CREDENTIAL') {
          try {
            await saveActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Waiting on credential upload' }, prismaClient as never);
          } catch {
            workflowStats.transientFailuresRecovered += 1;
            await saveActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Recovered save' }, prismaClient as never);
          }
          await dismissActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Credential request sent' }, prismaClient as never);
          return;
        }

        if (row.actionType === 'CONTINUE_REVIEW') {
          try {
            await saveActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Queued for review' }, prismaClient as never);
          } catch {
            workflowStats.transientFailuresRecovered += 1;
            await saveActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Recovered review queue' }, prismaClient as never);
          }
          if (random() < 0.5) {
            await setActionRecommendationStatus(row.actionId, 'pending', { actorId: `actor-${index}`, note: 'Moved back to backlog' }, prismaClient as never);
          }
          return;
        }

        try {
          await executeActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Verification complete' }, prismaClient as never);
        } catch {
          workflowStats.transientFailuresRecovered += 1;
          await executeActionRecommendation(row.actionId, { actorId: `actor-${index}`, note: 'Retry verification execute' }, prismaClient as never);
        }
      } catch (error) {
        throw new Error(`Workflow ${row.actionId} failed: ${error instanceof Error ? error.message : String(error)}`);
      }
    });

    await Promise.all(workflows);

    for (const row of prismaClient.listActionRows()) {
      const hydrated = prismaClient.getActionWithEvents(row.actionId);
      const history = validateStatusHistory(hydrated?.statusEvents ?? []);
      workflowStats.invalidTransitions += history.invalidTransitions;
      workflowStats.duplicateTerminalEvents += history.duplicateStates;

      const normalizedStatus = normalizeActionStatus(row.status);
      if (normalizedStatus === 'completed') {
        workflowStats.actionsCompleted += 1;
      } else if (normalizedStatus === 'skipped') {
        workflowStats.actionsSkipped += 1;
      } else if (normalizedStatus === 'in_progress') {
        workflowStats.actionsInProgress += 1;
      }

      const metadata = extractHiringAutomationMetadata(row.metadata);
      if (
        row.actionType === 'READY_TO_INTERVIEW'
        && normalizedStatus === 'completed'
        && (metadata?.workflowEffects.missingCredentials.length ?? 0) > 0
      ) {
        throw new Error(`Completed action still had unresolved dependencies: ${row.actionId}`);
      }
    }

    const debugRows = prismaClient.listActionRows().map((row) => `${row.actionId}(${row.actionType}):${row.status}`);
    console.info(`DEBUG_STATES ${debugRows.join(' ')}`);
    console.info(`ACTION_SIMULATION ${JSON.stringify(workflowStats)}`);

    expect(workflowStats.invalidTransitions).toBe(0);
    expect(workflowStats.duplicateTerminalEvents).toBe(0);
    expect(workflowStats.actionsCompleted + workflowStats.actionsSkipped + workflowStats.actionsInProgress).toBe(50);
  });
});
