function mulberry32(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state += 0x6D2B79F5;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4294967296;
  };
}

class InMemoryActionPrisma {
  private actions = new Map<string, ActionRecommendationRow>();
  private statusEvents: ActionStatusEventRow[] = [];
  private actionCounter = 0;
  private eventCounter = 0;
  private updateBarrierSize = 0;
  private updateBarrierArrival = 0;
  private updateBarrierResolvers: Array<() => void> = [];
  private failNextStatusEventCreateForActionIds = new Map<string, number>();

  public readonly actionRecommendation = {
    findMany: async (args?: { where?: { actionId?: { in?: string[] } } }) => {
      const rows = [...this.actions.values()].filter((row) => {
        const actionIds = args?.where?.actionId?.in;
        return !actionIds || actionIds.includes(row.actionId);
      });
      return rows.map((row) => this.cloneRow(row));
    },
    create: async (args: { data: any }) => {
      const id = `action-row-${++this.actionCounter}`;
      const createdAt = args.data.createdAt instanceof Date ? args.data.createdAt : new Date(args.data.createdAt);
      const row: ActionRecommendationRow = {
        id,
        actionId: args.data.actionId,
        actionType: args.data.actionType,
        storylineKey: args.data.storylineKey ?? null,
        sourceFindingIds: [...(args.data.sourceFindingIds ?? [])],
        predictionIds: [...(args.data.predictionIds ?? [])],
        targetEntityType: args.data.targetEntityType,
        targetEntityId: args.data.targetEntityId,
        targetEntityLabel: args.data.targetEntityLabel ?? null,
        recommendedAction: args.data.recommendedAction,
        priority: args.data.priority,
        priorityScore: args.data.priorityScore,
        confidence: args.data.confidence,
        explanation: args.data.explanation,
        evidence: toJsonValue(args.data.evidence ?? []),
        metadata: toJsonValue(args.data.metadata ?? {}),
        status: args.data.status,
        executedAt: null,
        dismissedAt: null,
        savedAt: null,
        createdAt,
        updatedAt: createdAt,
      };
      this.actions.set(row.actionId, row);

      const nestedEvents = args.data.statusEvents?.create ?? [];
      for (const event of nestedEvents) {
        this.statusEvents.push({
          id: `status-event-${++this.eventCounter}`,
          actionRecommendationId: row.id,
          fromStatus: event.fromStatus ?? null,
          toStatus: event.toStatus,
          actorId: event.actorId ?? null,
          note: event.note ?? null,
          metadata: toJsonValue(event.metadata ?? {}),
          createdAt: event.createdAt instanceof Date ? event.createdAt : new Date(event.createdAt),
        });
      }

      return this.cloneRow(row);
    },
    update: async (args: { where: { actionId: string }; data: Record<string, unknown> }) => {
      const row = this.requireAction(args.where.actionId);
      Object.assign(row, {
        ...args.data,
        sourceFindingIds: args.data.sourceFindingIds ? [...(args.data.sourceFindingIds as string[])] : row.sourceFindingIds,
        predictionIds: args.data.predictionIds ? [...(args.data.predictionIds as string[])] : row.predictionIds,
        evidence: args.data.evidence ? toJsonValue(args.data.evidence) : row.evidence,
        metadata: args.data.metadata ? toJsonValue(args.data.metadata) : row.metadata,
        updatedAt: new Date('2026-04-22T12:00:00.000Z'),
      });
      return this.cloneRow(row);
    },
    findUnique: async (args: { where: { actionId: string }; include?: { statusEvents?: unknown } }) => {
      const row = this.actions.get(args.where.actionId);
      if (!row) {
        return null;
      }
      return this.withInclude(row, args.include);
    },
    findUniqueOrThrow: async (args: { where: { actionId: string }; include?: { statusEvents?: unknown } }) => {
      const row = await this.actionRecommendation.findUnique(args);
      if (!row) {
        throw new Error(`Action not found: ${args.where.actionId}`);
      }
      return row;
    },
    updateMany: async (args: { where: { id: string; status: string }; data: Record<string, unknown> }) => {
      await this.waitForUpdateBarrier();
      const row = [...this.actions.values()].find((candidate) => candidate.id === args.where.id && candidate.status === args.where.status);
      if (!row) {
        return { count: 0 };
      }

      Object.assign(row, {
        ...args.data,
        updatedAt: new Date('2026-04-22T12:05:00.000Z'),
      });
      return { count: 1 };
    },
  };

  public readonly actionStatusEvent = {
    create: async (args: { data: Omit<ActionStatusEventRow, 'id'> }) => {
      const row = [...this.actions.values()].find((candidate) => candidate.id === args.data.actionRecommendationId);
      if (!row) {
        throw new Error(`Unknown action recommendation id: ${args.data.actionRecommendationId}`);
      }

      const remainingFailures = this.failNextStatusEventCreateForActionIds.get(row.actionId) ?? 0;
      if (remainingFailures > 0) {
        this.failNextStatusEventCreateForActionIds.set(row.actionId, remainingFailures - 1);
        throw new Error(`Injected status-event failure for ${row.actionId}`);
      }

      const created: ActionStatusEventRow = {
        id: `status-event-${++this.eventCounter}`,
        actionRecommendationId: args.data.actionRecommendationId,
        fromStatus: args.data.fromStatus ?? null,
        toStatus: args.data.toStatus,
        actorId: args.data.actorId ?? null,
        note: args.data.note ?? null,
        metadata: toJsonValue(args.data.metadata ?? {}),
        createdAt: args.data.createdAt instanceof Date ? args.data.createdAt : new Date(args.data.createdAt),
      };
      this.statusEvents.push(created);
      return toJsonValue(created);
    },
  };

  public async $transaction<T>(work: (tx: this) => Promise<T>): Promise<T> {
    const snapshot = {
      actions: new Map([...this.actions.entries()].map(([key, value]) => [key, this.cloneRow(value)])),
      statusEvents: this.statusEvents.map((event) => ({ ...event, createdAt: new Date(event.createdAt) })),
      actionCounter: this.actionCounter,
      eventCounter: this.eventCounter,
    };

    try {
      return await work(this);
    } catch (error) {
      this.actions = new Map(snapshot.actions.entries());
      this.statusEvents = snapshot.statusEvents;
      this.actionCounter = snapshot.actionCounter;
      this.eventCounter = snapshot.eventCounter;
      throw error;
    }
  }

  public enableConcurrentUpdateBarrier(target = 2): void {
    this.updateBarrierSize = target;
    this.updateBarrierArrival = 0;
    this.updateBarrierResolvers = [];
  }

  public injectStatusEventFailure(actionId: string, count = 1): void {
    this.failNextStatusEventCreateForActionIds.set(actionId, count);
  }

  public reset(): void {
    this.actions.clear();
    this.statusEvents = [];
    this.actionCounter = 0;
    this.eventCounter = 0;
    this.updateBarrierSize = 0;
    this.updateBarrierArrival = 0;
    this.updateBarrierResolvers = [];
    this.failNextStatusEventCreateForActionIds.clear();
  }

  public getAction(actionId: string): ActionRecommendationRow | null {
    const row = this.actions.get(actionId);
    return row ? this.cloneRow(row) : null;
  }

  public getActionWithEvents(actionId: string): (ActionRecommendationRow & { statusEvents: ActionStatusEventRow[] }) | null {
    const row = this.actions.get(actionId);
    return row ? this.withInclude(row, { statusEvents: true }) as (ActionRecommendationRow & { statusEvents: ActionStatusEventRow[] }) : null;
  }

  public listActionRows(): ActionRecommendationRow[] {
    return [...this.actions.values()].map((row) => this.cloneRow(row));
  }

  public async updateActionMetadata(actionId: string, metadata: Record<string, unknown>): Promise<void> {
    await this.actionRecommendation.update({
      where: { actionId },
      data: { metadata: toJsonValue(metadata) },
    });
  }

  private requireAction(actionId: string): ActionRecommendationRow {
    const row = this.actions.get(actionId);
    if (!row) {
      throw new Error(`Action not found: ${actionId}`);
    }
    return row;
  }

  private cloneRow(row: ActionRecommendationRow): ActionRecommendationRow {
    return {
      ...toJsonValue(row),
      createdAt: new Date(row.createdAt),
      updatedAt: new Date(row.updatedAt),
      executedAt: row.executedAt ? new Date(row.executedAt) : null,
      dismissedAt: row.dismissedAt ? new Date(row.dismissedAt) : null,
      savedAt: row.savedAt ? new Date(row.savedAt) : null,
    };
  }

  private withInclude(
    row: ActionRecommendationRow,
    include?: { statusEvents?: unknown },
  ): ActionRecommendationRow & { statusEvents?: ActionStatusEventRow[] } {
    const cloned = this.cloneRow(row) as ActionRecommendationRow & { statusEvents?: ActionStatusEventRow[] };
    if (include?.statusEvents) {
      cloned.statusEvents = this.statusEvents
        .filter((event) => event.actionRecommendationId === row.id)
        .sort((left, right) => right.createdAt.getTime() - left.createdAt.getTime())
        .map((event) => ({
          ...toJsonValue(event),
          createdAt: new Date(event.createdAt),
        }));
    }
    return cloned;
  }

  private async waitForUpdateBarrier(): Promise<void> {
    if (this.updateBarrierSize === 0) {
      return;
    }

    this.updateBarrierArrival += 1;
    if (this.updateBarrierArrival < this.updateBarrierSize) {
      await new Promise<void>((resolve) => {
        this.updateBarrierResolvers.push(resolve);
      });
      return;
    }

    const resolvers = [...this.updateBarrierResolvers];
    this.updateBarrierSize = 0;
    this.updateBarrierArrival = 0;
    this.updateBarrierResolvers = [];
    for (const resolve of resolvers) {
      resolve();
    }
  }
}

type ActionPrisma = InMemoryActionPrisma;

