#!/usr/bin/env node
/**
 * Generate docs/ops/route-map.md from apps/web/app/**\/page.tsx.
 *
 * Usage:
 *   node scripts/generate-route-map.mjs            # write route map
 *   node scripts/generate-route-map.mjs --check    # exit 1 if route map is out of date
 *
 * Why this exists: per BOARD-SCHEMA-3, the "Route map coverage" row
 * cannot move without an enforced, filesystem-derived route inventory.
 * This script walks `apps/web/app/**\/page.tsx`, normalizes path
 * segments (route groups, dynamic segments, optional catch-alls), and
 * emits a markdown table. The CI gate
 * (.github/workflows/route-map-gate.yml) re-runs this in --check mode
 * on every PR that touches `apps/web/app/`.
 *
 * Truth contract:
 *   - This script reads the filesystem; it does not introspect runtime
 *     auth, params, or response shape.
 *   - The "Auth" column is a static heuristic (presence of
 *     `auth-required` segment, `(authed)` group, or `clerkMiddleware`
 *     guard in middleware.ts). It is NOT a runtime assertion.
 *   - The "Notes" column is filled from a `// route-map: <note>`
 *     comment on the first 20 lines of the page module, if present.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative } from 'node:path';
import { execSync } from 'node:child_process';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = join(SCRIPT_DIR, '..');
const APP_DIR = join(REPO_ROOT, 'apps', 'web', 'app');
const OUT_PATH = join(REPO_ROOT, 'docs', 'ops', 'route-map.md');

const checkMode = process.argv.includes('--check');

function findPageFiles(dir) {
  // Use git ls-files for stable ordering and to honor .gitignore.
  const cmd = `git -C ${REPO_ROOT} ls-files "apps/web/app/**/page.tsx"`;
  return execSync(cmd, { encoding: 'utf-8' })
    .trim()
    .split('\n')
    .filter(Boolean)
    .map((p) => join(REPO_ROOT, p))
    .sort();
}

function pathToRoute(filePath) {
  const rel = relative(APP_DIR, filePath);
  const parts = rel.split('/').slice(0, -1); // drop the page.tsx
  const cleaned = parts
    .filter((seg) => !seg.startsWith('(') || !seg.endsWith(')')) // drop route groups
    .join('/');
  return '/' + cleaned;
}

function detectAuth(filePath) {
  const rel = relative(APP_DIR, filePath);
  if (rel.includes('(authed)') || rel.includes('auth-required')) return 'required';
  if (rel.startsWith('admin/') || rel.includes('/admin/')) return 'admin';
  if (rel.startsWith('clinician/') || rel.includes('/clinician/')) return 'clinician';
  if (rel.startsWith('employer/') || rel.includes('/employer/')) return 'employer';
  if (rel.startsWith('issuer/') || rel.includes('/issuer/')) return 'issuer';
  return 'public';
}

function detectDynamic(filePath) {
  const rel = relative(APP_DIR, filePath);
  if (rel.includes('[[')) return 'optional-catch-all';
  if (rel.includes('[...')) return 'catch-all';
  if (rel.match(/\[[a-zA-Z]+\]/)) return 'dynamic';
  return 'static';
}

function readRouteNote(filePath) {
  try {
    const src = readFileSync(filePath, 'utf-8').split('\n').slice(0, 20).join('\n');
    const m = src.match(/\/\/\s*route-map:\s*(.+)/);
    if (m) return m[1].trim();
  } catch {
    // ignore
  }
  return '';
}

function main() {
  const files = findPageFiles(APP_DIR);
  if (files.length === 0) {
    console.error('No page.tsx files found under apps/web/app/');
    process.exit(1);
  }

  const rows = files.map((file) => ({
    route: pathToRoute(file),
    file: relative(REPO_ROOT, file),
    auth: detectAuth(file),
    dynamic: detectDynamic(file),
    note: readRouteNote(file),
  }));

  const lines = [];
  lines.push('# VitalCV Route Map');
  lines.push('');
  lines.push('Generated by `scripts/generate-route-map.mjs` from `apps/web/app/**/page.tsx`.');
  lines.push('Do not edit by hand. CI re-runs the generator and fails the build if this file');
  lines.push('drifts from the filesystem (see `.github/workflows/route-map-gate.yml`).');
  lines.push('');
  lines.push(`**Routes:** ${rows.length}`);
  lines.push('');
  lines.push('## Schema');
  lines.push('');
  lines.push('| Column | Source |');
  lines.push('|---|---|');
  lines.push('| Route | URL path derived from file path; route groups `(name)` removed; dynamic segments preserved as `[name]` |');
  lines.push('| Auth | Static heuristic from path prefix or `(authed)` route group. NOT a runtime assertion. |');
  lines.push('| Type | `static`, `dynamic`, `catch-all`, or `optional-catch-all` |');
  lines.push('| Notes | First-line `// route-map: <note>` comment in the page module, if present |');
  lines.push('| File | Repo-relative path |');
  lines.push('');
  lines.push('## Routes');
  lines.push('');
  lines.push('| Route | Auth | Type | Notes | File |');
  lines.push('|---|---|---|---|---|');
  for (const r of rows) {
    const note = (r.note || '—').replace(/\|/g, '\\|');
    lines.push(
      `| \`${r.route}\` | ${r.auth} | ${r.dynamic} | ${note} | \`${r.file}\` |`,
    );
  }
  lines.push('');

  const output = lines.join('\n');

  if (checkMode) {
    if (!existsSync(OUT_PATH)) {
      console.error(
        `route-map: ${OUT_PATH} is missing. Run \`node scripts/generate-route-map.mjs\` and commit the result.`,
      );
      process.exit(1);
    }
    const current = readFileSync(OUT_PATH, 'utf-8');
    if (current !== output) {
      console.error(
        `route-map: ${OUT_PATH} is out of date. Run \`node scripts/generate-route-map.mjs\` and commit the result.`,
      );
      process.exit(1);
    }
    console.log(`route-map: ${rows.length} routes — up to date.`);
    return;
  }

  writeFileSync(OUT_PATH, output, 'utf-8');
  console.log(`route-map: wrote ${rows.length} routes to ${relative(REPO_ROOT, OUT_PATH)}`);
}

main();
